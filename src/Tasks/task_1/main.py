#!/usr/bin/env python3
# -*- coding: utf-8 -*-

# Парой называется класс с двумя полями, которые обычно
# имеют имена first и second. Требуется реализовать тип
# данных с помощью такого класса.
#
# Во всех заданиях обязательно должны присутствовать:
# метод инициализации __init__; метод должен контролировать
# значения аргументов на корректность; ввод с клавиатуры
# read; вывод на экран.
#
# Реализовать внешнюю функцию с именем make_тип(),
# где тип – тип реализуемой структуры. Функция должна
# получать в качестве аргументов значения для полей
# структуры и возвращать структуру требуемого типа.
#
# При передаче ошибочных параметров следует выводить
# сообщение и заканчивать работу.
#
# В раздел программы, начинающийся после инструкции
# if __name__ == "__main__": добавить код, демонстрирующий
# возможности разработанного класса.
#
# Поле first – дробное положительное число, цена товара.
# Поле second – целое положительное число, количество
# единиц товара.
#
# Реализовать метод cost() – вычисление стоимости товара.

from Tasks.task_1.make_pair import make_pair
from Tasks.task_1.pair import Pair


def main():
    try:
        first, second = Pair.read()
        product = make_pair(first, second)
    except (TypeError, ValueError) as error:
        print(f"Ошибка: {error}")
        raise SystemExit(1) from None

    product.display()
    print(f"Стоимость товара: {product.cost():.2f}")


if __name__ == "__main__":
    main()
